    TRIM(DELIVERY_ID,'') AS DELIVERY_ID,
    TRY_TO_TIMESTAMP_NTZ(DELIVERY_TIMESTAMP) AS DELIVERY_TIMESTAMP,
    TRY_CAST(INNINGS_NO AS INT) AS INNINGS_NO,
    TRY_CAST(OVER_NO AS INT) AS OVER_NO,
    TRY_CAST(BALL_IN_OVER AS INT) AS BALL_IN_OVER,
    IFNULL(TRY_CAST(RUNS_OFF_BAT AS INT),0) AS RUNS_OF_BAT,
    IFNULL(UPPER(EXTRA_TYPE),NULL) AS EXTRA_TYPE,
    IFNULL(TRY_CAST(EXTRA_RUNS AS INT),0) AS EXTRA_RUNS,
    IFNULL(TRY_CAST(TOTAL_RUNS AS INT),0) AS TOTAL_RUNS,
    -- TRY_CAST(CASE WHEN((UPPER(TRIM(IS_WICKET)))='FALSE' OR IS_WICKET=0 THEN 0 ELSE 1 END) 
    -- AS INT) AS IS_WICKET,
    TRY_CAST(TRIM(IS_WICKET) AS BOOLEAN) AS IS_WICKET,
    IFNULL(UPPER(TRIM(DISMISSAL_TYPE)),NULL) AS DISMISSAL_TYPE,
    TRY_CAST(BALL_SPEED_KMPH AS NUMERIC) AS BALL_SPEED_KMPH,
    TRIM(NON_STRIKER_ID) AS NON_STRINKER_ID,
    TRIM(SHOT_TYPE) AS SHOT_TYPE,
    TRIM(SHOT_REGION) AS SHOT_REGION,
    TRIM(MATCH_ID) AS MATCH_ID,
    TRY_TO_DATE(MATCH_DATE) AS MATCH_DATE,
    TRIM(MATCH_FORMAT) AS MATCH_FORMAT,
    UPPER(TRIM(TOURNAMENT_NAME)) AS TOURNAMENT_NAME,
    TRY_CAST(TRIM(SEASON) AS INT) AS SEASON,
    TRIM(MATCH_STAGE) AS MATCH_STAGE,
    UPPER(TRIM(TOSS_DECISION)) AS TOSS_DECISION,
    TRIM(VENUE_ID) AS VENUE_ID,
    UPPER(TRIM(VENUE_NAME)) AS VENUE_NAME,
    UPPER(TRIM(VENUE_CITY)) AS VENUE_CITY,
    UPPER(TRIM(VENUE_COUNTRY)) AS VENUE_COUNTRY,
    TRIM(BATTING_TEAM_ID) AS BATTING_TEAM_ID,
    UPPER(TRIM(BATTING_TEAM_NAME)) AS BATTING_TEAM_NAME,
    TRIM(BOWLING_TEAM_ID) AS BOWLING_TEAM_ID,
    UPPER(TRIM(BOWLING_TEAM_NAME)) AS BOWLING_TEAM_NAME,
    TRIM(BATSMAN_ID) AS BATSMAN_ID,
    UPPER(TRIM(BATSMAN_NAME)) AS BATSMAN_NAME,
    TRY_TO_DATE(BATSMAN_DOB) AS BATSMAN_DOB,
    UPPER(TRIM(BATSMAN_NATIONALITY)) AS BATSMAN_NATIONALITY,
    UPPER(TRIM(BATTING_HAND)) AS BATTING_HAND,
    UPPER(TRIM(BATSMAN_ROLE)) AS BATSMAN_ROLE,
    CASE WHEN BATSMAN_EMAIL like '%@%.com' THEN LOWER(TRIM(BATSMAN_EMAIL)) else null END AS BATSMAN_EMAIL,
    TRIM(BATSMAN_PHONE) AS BATSMAN_PHONE,--remain regex
    TRY_CAST(TRIM(BATSMAN_ICC_RATING) AS INT) AS BATSMAN_ICC_RATING,
    TRIM(BOWLER_ID) AS BOWLER_ID,
    UPPER(TRIM(BOWLER_NAME)) AS BOWLER_NAME,
    UPPER(TRIM(BOWLER_NATIONALITY)) AS BOWLER_NATIONALITY,
    UPPER(TRIM(BOWLING_STYLE)) AS BOWLING_STYLE,
    TRY_CAST(TRIM(BOWLER_ICC_RATING) AS INT) AS BOWLER_ICC_RATING,
    TRIM(CONTRACT_ID) AS CONTRACT_ID,
    UPPER(TRIM(CONTACT_GRADE)) AS CONTACT_GRADE,
    TRY_CAST(ANNUAL_RETAINER_USD AS NUMERIC) AS ANNUAL_RETAINER_USD,
    UPPER(TRIM(CONTRACT_STATUS)) AS CONTRACT_STATUS,
    TRIM(DRS_REVIEW_ID) AS DRS_REVIEW_ID,
    UPPER(TRIM(DRS_REVIEWED_BY)) AS DRS_REVIEWED_BY,
