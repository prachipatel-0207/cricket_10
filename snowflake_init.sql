-- Run as a role that may create a warehouse and database.
CREATE WAREHOUSE IF NOT EXISTS BANKING_WH
  WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 300 AUTO_RESUME = TRUE;
CREATE DATABASE IF NOT EXISTS CAPSTONE_DB;
USE DATABASE CAPSTONE_DB;
CREATE SCHEMA IF NOT EXISTS BRONZE;
CREATE SCHEMA IF NOT EXISTS SILVER;
CREATE SCHEMA IF NOT EXISTS GOLD;
USE SCHEMA BRONZE;

CREATE FILE FORMAT IF NOT EXISTS CSV_FILE_FORMAT
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('NULL', 'null', '') TRIM_SPACE = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;
CREATE STAGE IF NOT EXISTS MY_STAGE FILE_FORMAT = CSV_FILE_FORMAT;
CREATE TABLE IF NOT EXISTS FILE_AUDIT (
  AUDIT_ID INT AUTOINCREMENT,
  FILENAME VARCHAR(500) NOT NULL,
  ROWSLOADED INT DEFAULT 0,
  STATUS VARCHAR(500) NOT NULL,
  LOAD_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
